function capturarTextosES() {
  document.querySelectorAll("[data-i18n]").forEach((el) => { ES_HTML[el.dataset.i18n] ??= el.innerHTML; });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => { ES_HTML[el.dataset.i18nAria] ??= el.getAttribute("aria-label"); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { ES_HTML[el.dataset.i18nPh] ??= el.placeholder; });
  document.querySelectorAll("[data-i18n-content]").forEach((el) => { ES_HTML[el.dataset.i18nContent] ??= el.content; });
}

